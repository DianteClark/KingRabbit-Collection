// Records a known way to hole every Mini Golf hole within par + 1, using the brute-force solver.
// Run after changing the physics or a hole:  node tests/mini-golf-solutions.mjs
// The tests (mini-golf.test.mjs) replay these shots, so they stay fast.
import { writeFileSync } from 'node:fs';

const base = new URL('../games/mini-golf/logic/', import.meta.url);
const { HOLES, DAILY_HOLES } = await import(new URL('holes.js', base));
const { compileHole } = await import(new URL('physics.js', base));
const { solve } = await import(new URL('solver.js', base));

const out = {};
let bad = 0;
for (const h of [...HOLES, ...DAILY_HOLES]) {
  const t = Date.now();
  const sol = solve(compileHole(h), { limit: h.par + 1 });
  console.log(h.id.padEnd(4), h.name.padEnd(22), `par ${h.par}`, sol ? `in ${sol.strokes}` : 'NOT SOLVED', `${Date.now() - t}ms`);
  if (!sol || sol.strokes > h.par + 1) { bad++; continue; }
  out[h.id] = sol.shots.map((s) => [s.angle, s.power, s.wait]);
}
const body = Object.entries(out).map(([id, shots]) => `  '${id}': ${JSON.stringify(shots)},`).join('\n');
writeFileSync(new URL('solutions.js', base), `// Generated by tests/mini-golf-solutions.mjs: one known way to hole each hole ([angle, power, wait before the putt]).\n// Not loaded by the game; the tests replay these with the game's own physics.\nexport const SOLUTIONS = {\n${body}\n};\n`);
if (bad) { console.error(`${bad} holes could not be solved within par + 1`); process.exit(1); }
