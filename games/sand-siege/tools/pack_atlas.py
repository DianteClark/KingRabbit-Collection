#!/usr/bin/env python3
"""Pack every frame Sand Siege uses from the Battle of the Sands sheets into one small atlas.

Run from the repo root:  python3 games/sand-siege/tools/pack_atlas.py
Writes games/sand-siege/art/atlas.png and games/sand-siege/art/atlas.js (frame name -> [x, y, w, h]).
Art: Battle of the Sands by Aleksandr Makarov.
"""
import json
import os
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..', '..', '..')
SRC = os.path.join(ROOT, 'shared/assets/battle-of-the-sands/Battle-of-the-Sands-v.1.2')
OUT = os.path.join(os.path.dirname(__file__), '..', 'art')

def sheet(rel):
    return Image.open(os.path.join(SRC, rel)).convert('RGBA')

frames = []  # (name, image)

def add(name, img, x, y, w, h):
    frames.append((name, img.crop((x, y, x + w, y + h))))

TEAMS = {'b': 'Blue', 'r': 'Red'}
# Foot soldiers: 16 frames of 12x12 at y = 12 (idle 0-3, walk 4-7, attack 8-11, death 12-15), facing right.
for t, team in TEAMS.items():
    for art, file in (('inf', 'Infantry8x8'), ('hinf', 'HighInfantry8x8'), ('scout', 'Scout8x8')):
        img = sheet(f'Units/Sprites/{team}{file}.png')
        for i in range(16):
            add(f'{art}_{t}_{i}', img, 12 * i, 12, 12, 12)

# Vehicles: 3x3 blocks of facings (middle empty). Small 12x12 at (36 + 24c, 12 + 24r); big 24x24 at (12 + 32c, 232 + 32r).
VEH = {
    'recon': (False, 0, 3), 'tank': (False, 3, 0), 'truck': (False, 3, 6), 'harv': (False, 0, 0),
    'arty': (True, 0, 0), 'drone': (True, 3, 0), 'heavy': (True, 0, 3), 'flak': (True, 3, 3),
}
DIRS = {(0, 0): 'ul', (1, 0): 'u', (2, 0): 'ur', (0, 1): 'l', (2, 1): 'r', (0, 2): 'dl', (1, 2): 'd', (2, 2): 'dr'}
WANT = {'b': ['arty', 'heavy', 'flak', 'tank'], 'r': ['recon', 'tank', 'truck', 'drone', 'heavy', 'harv']}
for t, team in TEAMS.items():
    img = sheet(f'Units/Sprites/{team}Vehicle-v.1.1.png')
    for art in WANT[t]:
        big, c0, r0 = VEH[art]
        for (dc, dr), d in DIRS.items():
            c, r = c0 + dc, r0 + dr
            if big:
                add(f'{art}_{t}_{d}', img, 12 + 32 * c, 232 + 32 * r, 24, 24)
            else:
                add(f'{art}_{t}_{d}', img, 36 + 24 * c, 12 + 24 * r, 12, 12)

# Buildings: small 16x16 at x = 8 + 24i, y = 24; large 24x24 at x = 8 + 32i, y = 48.
for t, team in TEAMS.items():
    img = sheet(f'Buildings/{team}TeamBuildings.png')
    for i in range(8):
        add(f'bs_{t}_{i}', img, 8 + 24 * i, 24, 16, 16)
    for i in range(5):
        add(f'bl_{t}_{i}', img, 8 + 32 * i, 48, 24, 24)

fx = sheet('Effects/ExplosiveEffect.png')
for i in range(4):
    add(f'boom_{i}', fx, 12 * i, 0, 12, 12)
for name, file in (('shot', 'ShootingEffect'), ('death', 'SoldierDeathEffect')):
    img = sheet(f'Effects/{file}.png')
    for i in range(4):
        add(f'{name}_{i}', img, 8 * i, 0, 8, 8)

ui = sheet('UI/UI.png')
for name, (x, y) in {'c_tl': (0, 16), 'c_tr': (8, 16), 'c_bl': (0, 24), 'c_br': (8, 24)}.items():
    add(name, ui, x, y, 8, 8)

# Terrain tiles (8x8) used by the map painter, named by their place on the tileset.
tiles = sheet('Tileset/Tilemap.png')
TILES = set()
for p in [(24, 120), (40, 120), (24, 136), (40, 136), (8, 120), (8, 136), (24, 56), (40, 56), (40, 72),
          (24, 184), (40, 184), (24, 200), (40, 200), (40, 24), (40, 40), (72, 248), (8, 248), (24, 248),
          (72, 24), (80, 24), (24, 88), (40, 88)]:
    TILES.add(p)
for bx, by in [(56, 56), (56, 184), (96, 24), (56, 120)]:
    for c in range(3):
        for r in range(3):
            TILES.add((bx + 8 * c, by + 8 * r))
for x, y in sorted(TILES):
    add(f't_{x}_{y}', tiles, x, y, 8, 8)

# Shelf packing, tallest first, 1px gap.
W = 256
order = sorted(frames, key=lambda f: (-f[1].height, f[0]))
x = y = shelf = 0
rects = {}
for name, img in order:
    w, h = img.size
    if x + w > W:
        x = 0; y += shelf + 1; shelf = 0
    rects[name] = (x, y, w, h)
    x += w + 1
    shelf = max(shelf, h)
H = y + shelf
atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
for name, img in frames:
    rx, ry, _, _ = rects[name]
    atlas.paste(img, (rx, ry))
os.makedirs(OUT, exist_ok=True)
atlas.save(os.path.join(OUT, 'atlas.png'), optimize=True)
with open(os.path.join(OUT, 'atlas.js'), 'w') as f:
    f.write('// Generated by tools/pack_atlas.py from Battle of the Sands by Aleksandr Makarov. Do not edit by hand.\n')
    f.write('// name -> [x, y, w, h] on atlas.png\n')
    f.write('export const ATLAS = ' + json.dumps({k: list(v) for k, v in sorted(rects.items())}, separators=(',', ':')) + ';\n')
print(len(frames), 'frames', W, 'x', H)
