// First-time tips, placed automatically where each thing first shows up in a stage.
function addHints(st) {
  const m = st.map;
  const cols = m[0].length;
  const firstCol = (test) => { for (let c = 0; c < cols; c++) for (let r = 0; r < 15; r++) if (test(m[r][c])) return c; return -1; };
  const hints = [{ id: 'charge', x: 5, text: 'Tip: hold SHOOT, then let go for a charged shot.' }];
  const add = (id, ch, text, before = 6) => { const c = firstCol((x) => ch.includes(x)); if (c >= 0) hints.push({ id, x: Math.max(6, c - before), text }); };
  add('hardhat', 'm', 'Hard hats shrug off shots. Hit them when they peek out.');
  add('ladder', 'H', 'Ladder: hold UP to climb, DOWN on top to go down.');
  add('spike', '^v', 'Spikes hurt a lot. Bottomless pits cost a life.');
  add('conveyor', '<>', 'Conveyor belts push you along.');
  add('blink', '123', 'These blocks appear in turns. Wait, then jump.', 8);
  add('mover', 'M', 'Ride the moving platforms over the gaps.', 8);
  add('crack', '%', 'Cracked blocks break with the Drill Seeker.', 4);
  add('etank', 'E', 'An Energy Tank! Use it from the pause menu.', 4);
  add('checkpoint', 'C', 'Checkpoint: lose a life after this and you restart here.', -2);
  const door = m.findIndex((r) => r.includes('D')) >= 0 ? m.find((r) => r.includes('D')).indexOf('D') : -1;
  if (door >= 0) hints.push({ id: 'door', x: door - 8, text: 'Boss room ahead. Walk into the shutter.' });
  hints.sort((a, b) => a.x - b.x);
  return hints;
}
for (const st of Object.values(STAGES)) st.hints = addHints(st);

