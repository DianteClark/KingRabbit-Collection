// Stage maps. Each stage is a row of 30-column "screens" glued together, then a shutter door
// and a boss arena. 15 rows each (one screen tall), 8 px tiles.
//
//  .  empty           #  wall          =  wall (plain panels)   -  thin platform (jump up through)
//  H  ladder (2 wide) ^  spikes        v  ceiling spikes        <  >  conveyor belts
//  %  cracked block (a Drill Seeker breaks it)                  D  boss shutter door
//  P  start           C  checkpoint    B  boss                  M  moving platform (see movers)
//  1-3  appearing blocks, in turn (see blink)
//  enemies: w walker  m hard hat  h hopper  b bat  f flyer  t turret  s guard  c crawler
//  pickups: o small health  +  big health  *  big weapon energy  L  extra life  E  energy tank
import { TILE } from './constants.js';

const seg = (s) => s.trim().split('\n').map((r) => r.trim());
const join = (...segs) => segs[0].map((_, i) => segs.map((s) => s[i]).join(''));
// Maps are drawn with the floor at row 12, then lifted two rows so the floor sits at row 10:
// on screen that keeps everything standing on the floor just above the touch buttons. The top
// two rows (under the HUD buttons) go, and the bottom row repeats so pits stay open.
const lift = (rows) => [...rows.slice(2), rows[14], rows[14]];

/** Shutter door (left column) and a 27-column boss arena. plats: [[row, col0, col1]] thin platforms. */
function arena({ plats = [], ceil = true } = {}) {
  const W = 28;
  const rows = [];
  for (let r = 0; r < 15; r++) {
    let row;
    if (r <= 1) row = '#'.repeat(W);
    else if (r <= 9) row = '#' + '.'.repeat(W - 1);
    else if (r <= 11) row = 'D' + '.'.repeat(W - 1);
    else row = '#'.repeat(W);
    if (!ceil && r <= 1) row = '#' + '.'.repeat(W - 1);
    rows.push(row.split(''));
  }
  rows[11][21] = 'B';
  for (const [r, a, b] of plats) for (let c = a; c <= b; c++) rows[r][c] = '-';
  return rows.map((r) => r.join(''));
}

