// Campaign missions and skirmish maps as ASCII art (11 tiles wide for a portrait phone).
// Terrain: . sand   : dunes   o oasis   ^ mesa   ~ water
// Buildings: H/h HQ   F/f factory   C/c city   (upper case Blue, lower case Red)   n neutral city   m neutral factory
// Units overlay: I inf  L lancer  S scout  R recon  T tank  K heavy tank  A artillery  Q flak  D drone
//   (upper case Blue, lower case Red; any other character is empty)

const swapCase = (ch) => (ch === ch.toUpperCase() ? ch.toLowerCase() : ch.toUpperCase());

/** Build a fair map from its top half: the bottom is the top turned 180 degrees with sides swapped. */
function mirror(top, h) {
  const w = top[0].length;
  const rows = [];
  for (let y = 0; y < h; y++) {
    if (y < top.length) { rows.push(top[y]); continue; }
    const src = top[h - 1 - y];
    let r = '';
    for (let x = 0; x < w; x++) {
      const ch = src[w - 1 - x];
      r += /[A-Za-z]/.test(ch) && !'nmo'.includes(ch) ? swapCase(ch) : ch;
    }
    rows.push(r);
  }
  return rows;
}

